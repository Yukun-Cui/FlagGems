def histogramdd_linspace_from_tensor_kernel(
    out_ptr,
    min_ptr,
    max_ptr,
    d,
    steps,
    inv_denom,
    BLOCK_SIZE: tl.constexpr,
):
    """Device-side linspace whose endpoints are read from ``min_ptr``/``max_ptr``.

    Same value formula as ``histogramdd_linspace_kernel``, but the endpoints stay
    on the device: they are loaded from column ``d`` of the min/max reduction
    outputs rather than passed as host scalars. This keeps the data-derived path
    free of ``.item()``/``.tolist()`` synchronisation, so it is safe under graph
    capture. Degenerate columns (min == max) are widened to a unit interval here,
    matching the host path.
    """
    # Match torch.linspace, which computes in the output dtype: accumulating in
    # fp64 for an fp32 output shifts interior edges by ~1 ulp versus ATen.
    lo = tl.load(min_ptr + d)
    hi = tl.load(max_ptr + d)
    # Widen a degenerate range exactly as the host path does.
    degenerate = lo == hi
    lo = tl.where(degenerate, lo - 0.5, lo)
    hi = tl.where(degenerate, hi + 0.5, hi)
    # ``inv_denom`` is 1/(steps-1), computed on the host so this stays a multiply
    # (``steps`` is a runtime arg, not a constexpr, so it cannot be used in Python
    # arithmetic here).
    step = (hi - lo) * inv_denom

    pid = ext.program_id(0)
    idx = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = idx < steps
    val = lo + step * idx.to(lo.dtype)
    # The final edge is pinned to the exact endpoint, as torch.linspace does, so
    # accumulated rounding cannot push it past the data maximum. Guarded on
    # steps > 1: with a single edge, index 0 is both first and last and must stay
    # at the (widened) low endpoint.
    val = tl.where((steps > 1) & (idx == steps - 1), hi, val)
    tl.store(out_ptr + idx, val, mask=mask)


