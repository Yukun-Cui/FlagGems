def _linspace(start, end, steps, dtype, device):
    """Build a 1-D tensor of ``steps`` values linearly spaced from start to end.

    The computation is done by a Triton kernel for steps >= 2; steps == 1
    returns a single-element tensor holding ``start``.
    """
    out = torch.empty((steps,), dtype=dtype, device=device)
    if steps <= 0:
        return out
    if steps == 1:
        out.fill_(start)
        return out
    step = (float(end) - float(start)) / (steps - 1)
    # Each program writes a contiguous chunk of the 1-D edge tensor; 1024 is a
    # safe power-of-two tile that amortizes launch overhead for typical bin counts.
    BLOCK_SIZE = 1024
    grid = (triton.cdiv(steps, BLOCK_SIZE),)
    with torch_device_fn.device(device):
        histogramdd_linspace_kernel[grid](
            out, float(start), float(end), step, steps, BLOCK_SIZE=BLOCK_SIZE
        )
    return out


def _histogramdd_bin_edges_impl(
    self, bins, *, range=None, weight=None, density=False, out=None
):
    if self.dim() < 2:
        raise RuntimeError(
            "torch.histogramdd: input tensor should have at least 2 dimensions"
        )

    N = self.shape[-1]
    if len(bins) != N:
        raise RuntimeError(
            "histogramdd: The size of bins must be equal to the innermost dimension of the input."
        )

    # ``range`` shadows the built-in; keep the original name for the public API
    # but use ``range_`` locally and the built-in via ``builtins.range``.
    range_ = range
    range = builtins.range

    if range_ is not None:
        if len(range_) != 2 * N:
            raise RuntimeError(
                f"torch.histogramdd: for a {N}-dimensional histogram range "
                f"should have {2 * N} elements, but got {len(range_)}"
            )
        ranges = [(float(range_[2 * d]), float(range_[2 * d + 1])) for d in range(N)]
        # ATen rejects a non-finite explicit range up front, with the same wording
        # it uses for a non-finite data range. Without this the edges themselves
        # come back non-finite instead of raising.
        for d in range(N):
            lo, hi = ranges[d]
            if not (math.isfinite(lo) and math.isfinite(hi)):
                raise RuntimeError(
                    f"torch.histogramdd: dimension {d}'s range "
                    f"[{lo:g}, {hi:g}] is not finite"
                )
    else:
        ranges = [None] * N

    # An empty innermost dimension means there are no histogram dimensions at all,
    # so there are no edges to produce. Handled before the reshape below because
    # reshape(-1, 0) cannot infer the leading extent.
    if N == 0:
        return () if out is None else out

    # Flatten all leading dimensions so input becomes (M, N) C-contiguous.
    inp2d = self.reshape(-1, N).contiguous()

    col_min = col_max = None
    if range_ is None:
        # PyTorch falls back to a [0, 1] range when the input has no points, so
        # the per-column reduction is only meaningful when there is data.
        if inp2d.shape[0] == 0:
            empty_min_max = (0.0, 1.0)
        else:
            empty_min_max = None
            col_min, col_max, nonfinite = _compute_col_minmax(inp2d, N)
            # torch's histogramdd raises when a dimension's range is non-finite.
            # Deciding to raise is inherently a host-side branch, so it needs the
            # flag's value; the min/max values themselves stay on the device and are
            # consumed by histogramdd_linspace_from_tensor_kernel (no second pass
            # over the input, no host col.min()/col.max()).
            #
            # The read is skipped while a graph is capturing: an exception cannot be
            # raised from a replay anyway, and reading here would break capture. Eager
            # execution keeps full error parity with ATen; under capture the edges are
            # computed from the propagated NaN instead, which is what the recorded
            # kernels would produce.
            if not _is_capturing(inp2d.device):
                nonfinite_list = nonfinite.tolist()
                if any(nonfinite_list):
                    # The kernel stores a per-column count, so test for non-zero.
                    bad_d = next(i for i, v in enumerate(nonfinite_list) if v)
                    lo, hi = col_min[bad_d].item(), col_max[bad_d].item()
                    raise RuntimeError(
                        f"torch.histogramdd: dimension {bad_d}'s range "
                        f"[{lo:g}, {hi:g}] is not finite"
                    )

    edges = []
    for d in range(N):
        nb = int(bins[d])
        num_edges = nb + 1
        # ATen builds the edges with linspace(steps=bins+1), so bins == -1 (zero
        # steps) and bins == 0 (one step) are both legal and only bins <= -2 is
        # rejected -- by linspace itself, with this message. Clamping the negative
        # count to zero instead would silently accept those inputs.
        if num_edges < 0:
            raise RuntimeError("number of steps must be non-negative")

        if range_ is not None:
            left, right = ranges[d]
            if left > right:
                raise RuntimeError(
                    f"torch.histogramdd: min should not exceed max, but got "
                    f"min {left} max {right} for dimension {d}"
                )
        elif empty_min_max is None:
            # Data-derived endpoints stay on the device: the linspace kernel reads
            # column d of col_min/col_max itself (including the degenerate-range
            # widening), so nothing is materialised on the host here. Finiteness was
            # already validated above.
            edges.append(
                _linspace_from_tensor(
                    col_min, col_max, d, num_edges, self.dtype, self.device
                )
            )
            continue
        else:
            left, right = empty_min_max

        # When the data (or explicit range) is degenerate (min == max), PyTorch
        # widens the range to a unit interval centred on the value.
        if left == right:
            # Widening happens before the edge count is considered, so a single
            # edge is the *widened* left endpoint: ATen returns [2.0] for a
            # constant-2.5 column with bins=0.
            left = left - 0.5
            right = right + 0.5
            if num_edges == 1:
                edges.append(torch.tensor([left], dtype=self.dtype, device=self.device))
                continue

        edges.append(_linspace(left, right, num_edges, self.dtype, self.device))

    edges_tuple = tuple(edges)

    if out is not None:
        # ATen validates the out list before writing: the length must match the
        # number of histogram dimensions, and each output's dtype must equal the
        # input's (it raises rather than casting, so ``copy_`` alone would silently
        # accept an fp64 out for an fp32 input).
        if len(out) != N:
            raise RuntimeError(
                f"_histogramdd_bin_edges: expected out to have {N} tensors, "
                f"got {len(out)}"
            )
        for d in range(N):
            if out[d].dtype != self.dtype:
                raise RuntimeError(
                    f"Expected out tensor to have dtype {self.dtype}, but got "
                    f"{out[d].dtype} instead"
                )
            if out[d].device != self.device:
                raise RuntimeError(
                    f"Expected out tensor to have device {self.device}, but got "
                    f"{out[d].device} instead"
                )
        for d in range(N):
            expected = edges_tuple[d].numel()
            if out[d].numel() != expected:
                # Matches ATen, which resizes a mismatched output in place (and
                # warns when it had elements) rather than rejecting it.
                out[d].resize_(expected)
            out[d].copy_(edges_tuple[d])
        return out

    return edges_tuple


